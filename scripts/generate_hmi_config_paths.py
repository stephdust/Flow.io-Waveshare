#!/usr/bin/env python3
"""Generate the shared Nextion config tree from the resolved Web ConfigStore metadata.

Single source of truth: cfg_tree_aliases and cfg_tree_virtual_branches in the
profile-specific data/webinterface/cfgmods.json, itself assembled from each
module's text/cfgmods.fr.json by generate_config_docs.py.

The generated C++ data is *not* edited by hand or maintained as a second list.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SOURCE = ROOT / "data/webinterface/cfgmods.json"
DEFAULT_OUTPUT = ROOT / "src/Modules/HMIModule/ConfigMenuPaths_Generated.h"


def valid_path(value: object, *, segment: bool = False) -> str:
    if not isinstance(value, str) or not value:
        raise ValueError(f"Empty or invalid ConfigStore path: {value!r}")
    if value.strip() != value or any(not part or part in (".", "..") for part in value.split("/")):
        raise ValueError(f"Invalid ConfigStore path: {value!r}")
    if segment and "/" in value:
        raise ValueError(f"Virtual branch child is not a single segment: {value!r}")
    if any(ord(ch) < 32 or ord(ch) > 126 or ch in '"\\' for ch in value):
        raise ValueError(f"Non-ASCII or unsafe ConfigStore path: {value!r}")
    return value


def load_tree(source: Path) -> tuple[list[tuple[str, str]], list[tuple[str, list[str]]]]:
    payload = json.loads(source.read_text(encoding="utf-8"))
    meta = payload.get("meta")
    if not isinstance(meta, dict):
        raise ValueError("Missing Web cfgmods meta: did you run generate_config_docs.py?")
    raw_aliases = meta.get("cfg_tree_aliases")
    raw_branches = meta.get("cfg_tree_virtual_branches")
    if not isinstance(raw_aliases, list) or not isinstance(raw_branches, list):
        raise ValueError("Web metadata lacks cfg_tree_aliases/cfg_tree_virtual_branches")

    aliases: dict[str, str] = {}
    stores: dict[str, str] = {}
    for item in raw_aliases:
        if not isinstance(item, dict):
            raise ValueError("Invalid cfg_tree_aliases item")
        display = valid_path(item.get("display"))
        store = valid_path(item.get("store"))
        if display in aliases and aliases[display] != store:
            raise ValueError(f"Conflicting display alias {display}")
        if store in stores and stores[store] != display:
            raise ValueError(f"Conflicting ConfigStore alias {store}")
        aliases[display], stores[store] = store, display

    branches: dict[str, list[str]] = {}
    for item in raw_branches:
        if not isinstance(item, dict):
            raise ValueError("Invalid cfg_tree_virtual_branches item")
        branch = valid_path(item.get("display"))
        children = item.get("children")
        if not isinstance(children, list):
            raise ValueError(f"Invalid virtual branch children for {branch}")
        if branch in branches:
            raise ValueError(f"Duplicate virtual branch {branch}")
        branches[branch] = sorted(set(valid_path(child, segment=True) for child in children))

    for path in branches:
        if path in aliases:
            raise ValueError(f"Virtual path also maps to a real module: {path}")

    # Longest-prefix match in either direction: a subtree keeps its suffix.
    alias_list = sorted(((display, store) for display, store in aliases.items()),
                        key=lambda pair: pair[0])
    branch_list = sorted(branches.items())
    return alias_list, branch_list


def generate(source: Path) -> str:
    aliases, branches = load_tree(source)
    parts = [
        "#pragma once",
        "// GENERATED by scripts/generate_hmi_config_paths.py. DO NOT EDIT.",
        "// Only source: Web ConfigStore cfg_tree_aliases / cfg_tree_virtual_branches.",
        "// Included from inside namespace HmiConfigPaths, after struct declarations.",
        "",
        "static constexpr Alias kAliases[] = {",
    ]
    for display, store in aliases:
        parts.append(f'    {{"{store}", "{display}"}},')
    parts.extend(["};", "", "static constexpr const char* kVirtualChildren[] = {"])

    offsets = []
    offset = 0
    for branch, children in branches:
        offsets.append((branch, offset, len(children)))
        for child in children:
            parts.append(f'    "{branch}/{child}",')
        offset += len(children)

    parts.extend(["};", "", "static constexpr VirtualBranch kVirtualBranches[] = {"])
    for branch, first, count in offsets:
        parts.append(f'    {{"{branch}", {first}U, {count}U}},')
    parts.extend(["};", ""])
    return "\n".join(parts)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true",
                        help="fail if C++ output differs from Web metadata")
    args = parser.parse_args()
    rendered = generate(args.source)
    previous = args.output.read_text(encoding="utf-8") if args.output.exists() else ""
    if args.check:
        if previous != rendered:
            raise SystemExit("FAIL: generated Nextion tree differs from Web metadata")
    elif previous != rendered:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(rendered, encoding="utf-8")
    aliases, branches = load_tree(args.source)
    print(f"PASS: shared Web/Nextion tree: {len(aliases)} aliases, "
          f"{len(branches)} virtual branches, "
          f"{sum(len(children) for _, children in branches)} virtual children")


if __name__ == "__main__":
    main()
